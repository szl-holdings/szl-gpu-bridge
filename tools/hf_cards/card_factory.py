"""Render conservative cards from supplied metadata, without inventing evidence."""

from __future__ import annotations

import json

REGISTRY = {
    "github_org": "https://github.com/szl-holdings",
    "site": "https://szlholdings.com",
    "sponsors": "https://szlholdings.com/sponsors.html",
    "receipts_chain": "https://huggingface.co/datasets/SZLHOLDINGS/frontier-54-runs",
    "sdk_repo": "https://github.com/szl-holdings/szl-gpu-bridge/tree/main/sdk",
    "docs_autonomy": "https://github.com/szl-holdings/szl-gpu-bridge/blob/main/docs/AUTONOMY_LADDER.md",
    "docs_curriculum": "https://github.com/szl-holdings/szl-gpu-bridge/blob/main/docs/OUROBOROS_CURRICULUM.md",
    "docs_runbook": "https://github.com/szl-holdings/szl-gpu-bridge/blob/main/docs/NONSTOP_TRAINING_RUNBOOK.md",
    "dashboard": "https://szlholdings-szlholdings-si.hf.space",
    "anatomy": "https://szlholdings-anatomy.hf.space",
    "nexus": "https://szlholdings-nexus.hf.space",
}


def _card(*, kind, rid, name, tagline, what, investor, license_id=None,
          metadata=None, provenance="", rows="", **unused):
    # JSON-quoted scalars are valid YAML; preserve the SDK, base model and
    # license metadata actually supplied by the repository, including lists.
    card = dict(metadata or {})
    if license_id is not None:
        card["license"] = license_id
    if kind == "space" and not card.get("sdk"):
        raise ValueError("Space SDK metadata is required; do not guess docker")
    header = "\n".join(f"{json.dumps(str(k))}: {json.dumps(v)}" for k, v in card.items())
    license_text = json.dumps(card["license"]) if card.get("license") else "Unverified; no license supplied"
    prefix = {"model": "", "dataset": "datasets/", "space": "spaces/"}[kind]
    row_text = f"\n- Declared rows (not recounted): {rows}" if rows else ""
    return f"""---
{header}
---

# {name}

> {tagline}

## What this is

{what}

## Evidence and provenance

- Repository: https://huggingface.co/{prefix}{rid}
- License metadata (not an independent rights assessment): {license_text}
- Training, deployment, quality and performance: **UNVERIFIED by this generator**.
- Estate receipts index: {REGISTRY['receipts_chain']}. This index is not an artifact-specific evaluation receipt.{row_text}
{provenance}

## Next qualification step

Bind this artifact's exact revision, upstream licenses, data revisions and held-out evaluation receipts before making capability or promotion claims.

{investor}

Generated by tools/hf_cards. Links are supplied references; this card does not claim they were checked.
"""


def model_card(*, metrics=None, radar_axes=None, radar_values=None, **kwargs):
    if metrics or radar_axes or radar_values:
        raise ValueError("Attach artifact-specific measurement evidence before rendering metrics")
    return _card(kind="model", **kwargs)


def dataset_card(**kwargs):
    return _card(kind="dataset", **kwargs)


def space_card(**kwargs):
    return _card(kind="space", **kwargs)
