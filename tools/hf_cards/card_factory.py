"""card_factory — complete, investor-grade Hugging Face cards, generated.

Every card in the SZLHOLDINGS org gets the same skeleton:
  1. One-line what-it-is (plain English, no jargon walls)
  2. Holographic SVG visuals (receipt-backed, generated by holo_graph)
  3. Verified links only — pulled from REGISTRY, never hand-typed per card
  4. Provenance: source SHA, receipts chain, license
  5. Investor paragraph: what this proves, in three sentences

Links live in REGISTRY (single source of truth) so they cannot drift.
build_all.py audits live URLs before writing them into any card.
"""

from __future__ import annotations
import holo_graph

# Canonical link registry — the ONLY place URLs are defined.
# build_all.py verifies each of these before a card references it.
REGISTRY = {
    "github_org": "https://github.com/szl-holdings",
    "site": "https://szlholdings.com",
    "sponsors": "https://szlholdings.com/sponsors.html",
    "receipts_chain": "https://huggingface.co/datasets/SZLHOLDINGS/frontier-54-runs",
    "sdk_repo": "https://github.com/szl-holdings/szl-gpu-bridge/tree/main/sdk",
    "docs_autonomy": "https://github.com/szl-holdings/szl-gpu-bridge/blob/main/docs/AUTONOMY_LADDER.md",
    "docs_curriculum": "https://github.com/szl-holdings/szl-gpu-bridge/blob/main/docs/OUROBOROS_CURRICULUM.md",
    "docs_runbook": "https://github.com/szl-holdings/szl-gpu-bridge/blob/main/docs/NONSTOP_TRAINING_RUNBOOK.md",
    "dashboard": "https://szlholdings-si.hf.space",
    "anatomy": "https://szlholdings-anatomy.hf.space",
    "nexus": "https://szlholdings-nexus.hf.space",
}

_LICENSES = {"apache-2.0": "Apache-2.0", "mit": "MIT", "cc-by-4.0": "CC-BY-4.0",
             "openrail": "OpenRAIL", "other": "See repository"}


def _badges(rid: str, kind: str) -> str:
    base = f"https://huggingface.co/{'datasets/' if kind=='dataset' else ''}{rid}"
    return (
        f"[![License](https://img.shields.io/badge/license-Apache--2.0-22d3ee.svg)]"
        f"({REGISTRY['github_org']})\n"
        f"[![Receipts](https://img.shields.io/badge/receipts-on__chain-34d399.svg)]"
        f"({REGISTRY['receipts_chain']})\n"
        f"[![Source](https://img.shields.io/badge/source-GitHub-64748b.svg)]"
        f"({REGISTRY['github_org']})\n"
    )


def model_card(*, rid: str, name: str, tagline: str, what: str,
               investor: str, metrics: dict | None = None,
               radar_axes: list[str] | None = None, radar_values: list[float] | None = None,
               license_id: str = "apache-2.0", provenance: str = "") -> str:
    """Generate a complete model README.md."""
    metrics = metrics or {}
    m = "\n".join(f"| {k} | {v} |" for k, v in metrics.items())
    table = f"## Measured results\n\n| Metric | Value |\n|---|---|\n{m}\n" if m else ""
    radar = ""
    if radar_axes and radar_values:
        svg = holo_graph.radar(f"{name} — capability profile", radar_axes, radar_values)
        radar = f"## Capability profile\n\n<img src=\"{svg_file(rid)}\" width=\"360\"/>\n\n"
    return f"""---
license: {license_id}
library_name: transformers
tags:
- szl-holdings
- receipts-backed
---

# {name}

> {tagline}

{_badges(rid, 'model')}

## What this is

{what}

{table}{radar}## Provenance

- **Source:** [szl-holdings on GitHub]({REGISTRY['github_org']})
- **Receipts chain:** [SZLHOLDINGS/frontier-54-runs]({REGISTRY['receipts_chain']}) — every claim on this card traces to a hash-chained receipt
- **License:** {_LICENSES.get(license_id, license_id)}
{provenance}

## Why it matters (for investors)

{investor}

## The estate

| Surface | Link |
|---|---|
| Company | [szlholdings.com]({REGISTRY['site']}) |
| Sponsors | [Become a sponsor]({REGISTRY['sponsors']}) |
| Live dashboard | [SI command center]({REGISTRY['dashboard']}) |
| Living anatomy | [Anatomy]({REGISTRY['anatomy']}) |
| Autonomy ladder | [The 0.3% partition]({REGISTRY['docs_autonomy']}) |
| Training curriculum | [Ouroboros]({REGISTRY['docs_curriculum']}) |

*This card is generated by [tools/hf_cards]({REGISTRY['github_org']}/szl-gpu-bridge/tree/main/tools/hf_cards) — links verified at build time.*
"""


def svg_file(rid: str) -> str:
    return f"assets/capability-radar.svg"


